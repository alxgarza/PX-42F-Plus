#!/usr/bin/env python3
"""Converts a PNG into a 1-bit C bitmap for display_draw_bitmap().

Usage:
    python3 images/gen_image.py images/splash.png splash_image

writes images/splash_image.c, defining `splash_image` (a display_image_t,
see images/image.h). Dark pixels (gray < 128, alpha >= 128) become black;
everything else white. The PNG should be 250x122 (the full screen) --
smaller images are drawn from the top-left corner.

Reuses the dependency-free PNG decoder from fonts/gen_font.py, so the same
limits apply: 8-bit depth, gray/RGB/gray+alpha/RGBA, not interlaced, not
palette-based. Export from your image editor accordingly.
"""
import os
import sys

sys.dont_write_bytecode = True  # no __pycache__ in the source folders
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'fonts'))
from gen_font import decode_png, pixel_is_ink  # noqa: E402


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    png_path, name = sys.argv[1], sys.argv[2]
    w, h, bpp, color_type, raster = decode_png(png_path)
    if w > 250 or h > 122:
        sys.exit(f'{png_path}: {w}x{h} is larger than the 250x122 screen')

    stride = (w + 7) // 8
    out = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            off = (y * w + x) * bpp
            if pixel_is_ink(raster[off:off + bpp], bpp, color_type):
                out[y * stride + x // 8] |= 0x80 >> (x % 8)

    lines = [f'/* Generated by images/gen_image.py from {os.path.basename(png_path)} -- do not edit by hand. */',
             '#include "image.h"',
             '',
             f'static const uint8_t {name}_bits[] = {{']
    for y in range(h):
        row = out[y * stride:(y + 1) * stride]
        lines.append('    ' + ', '.join(f'0x{b:02X}' for b in row) + ',')
    lines += ['};',
              '',
              f'const display_image_t {name} = {{',
              f'    .width = {w},',
              f'    .height = {h},',
              f'    .data = {name}_bits,',
              '};',
              '']
    c_path = os.path.join(os.path.dirname(os.path.abspath(png_path)), f'{name}.c')
    with open(c_path, 'w') as f:
        f.write('\n'.join(lines))
    print(f'wrote {c_path} ({w}x{h})')


if __name__ == '__main__':
    main()
