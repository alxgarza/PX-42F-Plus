/* Each character occupies 30 bytes: two 15-byte bands stacked vertically
 * (24px tall total), each band covering 5 block-columns x 3 bytes (10px
 * wide). 128 entries, one per raw byte value 0-127 -- entry N is drawn for
 * character code N directly, no remapping. In particular, Free42's raw
 * ellipsis marker (byte 28, used by display_line() when a value has to be
 * truncated from the front) draws whatever glyph lives at entry 28, same
 * as any other code point.
 *
 * Characters are drawn with a 1px gap (11px total advance), which is odd,
 * so consecutive characters in a string land on alternating even/odd
 * pixel columns -- an even pixel_col is a plain block-aligned byte copy,
 * an odd one needs bit-shifting between two adjacent framebuffer blocks.
 * Confirmed ST7305 bit layout for one block byte (2px wide x 4 rows):
 * bit pairs 7:6, 5:4, 3:2, 1:0 are rows 0-3 of this byte's band, each
 * pair's high bit = left pixel, low bit = right pixel. So within a byte,
 * the "left column" bits are at positions 7,5,3,1 (mask 0xAA) and the
 * "right column" bits are at positions 6,4,2,0 (mask 0x55). */
#define FONT_CHAR_HEIGHT_BLOCKS 2   /* 2 stacked 12px bands = 24px tall */
#define FONT_CHAR_WIDTH_BLOCKS  5   /* 5 block-columns = 10px wide */
#define FONT_BAND_BYTES         (FONT_CHAR_WIDTH_BLOCKS * 3) /* 15 */
#define FONT_BYTES_PER_CHAR     (FONT_CHAR_HEIGHT_BLOCKS * FONT_BAND_BYTES) /* 30 */
#define FONT_FIRST_CHAR         0   /* table entry 0 is code point 0 */
#define FONT_LAST_CHAR          127 /* 128 entries: 0..127 inclusive */
#define FONT_CHAR_ADVANCE_PX    11  /* 10px glyph + 1px gap */

/* In-memory framebuffer, block-addressed (see DISP_BLOCK_COLS/ROWS in
 * display.h). +1 row of headroom so a character drawn starting at the
 * last valid block-row can't write past the end of the array (its bottom
 * band lands one block-row below where it started). */
static disp_block_t disp_row_buffer[DISP_BLOCK_ROWS + 1][DISP_BLOCK_COLS];

void display_clear(void) {
    memset(disp_row_buffer, 0, sizeof(disp_row_buffer));
}

void display_fill(uint8_t value) {
    memset(disp_row_buffer, value, sizeof(disp_row_buffer));
}

uint8_t display_draw_char(char c, uint8_t pixel_col, uint8_t block_row, uint8_t color) {
    if ((uint8_t) c < FONT_FIRST_CHAR || (uint8_t) c > FONT_LAST_CHAR)
        return pixel_col; /* not in the table -- skip rather than read garbage */

    uint8_t block_col = pixel_col >> 1;
    int odd = pixel_col & 1;

    /* Bounds check: a character drawn past the edge of the framebuffer
     * would write into whatever memory follows disp_row_buffer, corrupting
     * unrelated globals instead of just clipping visually -- silently
     * drop it instead of ever writing out of bounds. The odd case spills
     * one extra block-column past the glyph's own width (see below), so
     * it needs one more column of headroom than the even case. */
    unsigned last_index = (unsigned) block_col + FONT_CHAR_WIDTH_BLOCKS + (odd ? 1 : 0);
    if (last_index > DISP_BLOCK_COLS)
        return pixel_col;
    if (block_row >= DISP_BLOCK_ROWS)
        return pixel_col;

    const uint8_t *src = font_24x10 + ((uint8_t) c - FONT_FIRST_CHAR) * FONT_BYTES_PER_CHAR;

    for (int band = 0; band < FONT_CHAR_HEIGHT_BLOCKS; band++) {
        uint8_t *dst_row = (uint8_t *) disp_row_buffer[block_row + band];
        const uint8_t *src_band = src + band * FONT_BAND_BYTES;

        if (!odd) {
            /* Block-aligned: plain byte copy, one block-column at a time. */
            for (int i = 0; i < FONT_BAND_BYTES; i++)
                dst_row[block_col * 3 + i] = src_band[i] ^ color;
        } else {
            /* Odd pixel start: each glyph column's byte splits across two
             * destination blocks. Its own left-pixel bits (0xAA) shift
             * right by one into the current block's right-pixel slot;
             * its right-pixel bits (0x55) shift left by one into the
             * next block's left-pixel slot. Clearing only the slot about
             * to be written (not the whole byte) is what lets adjacent
             * glyph columns share a block without clobbering each other. */
            for (int col = 0; col < FONT_CHAR_WIDTH_BLOCKS; col++) {
                for (int b = 0; b < 3; b++) {
                    uint8_t v = src_band[col * 3 + b] ^ color;
                    int cur = (block_col + col) * 3 + b;
                    int nxt = (block_col + col + 1) * 3 + b;
                    dst_row[cur] = (uint8_t) ((dst_row[cur] & 0xAA) | ((v & 0xAA) >> 1));
                    dst_row[nxt] = (uint8_t) ((dst_row[nxt] & 0x55) | ((v & 0x55) << 1));
                }
            }
        }
    }

    return pixel_col + FONT_CHAR_ADVANCE_PX;
}

uint8_t display_draw_string(const char *s, uint8_t pixel_col, uint8_t block_row, uint8_t color) {
    while (*s)
        pixel_col = display_draw_char(*s++, pixel_col, block_row, color);
    return pixel_col;
}

/* Sets the write window for block-rows [start_row, start_row+num_rows).
 * Confirmed against the working AVR reference (buffRows_2_disp): despite
 * the command names, CASET addresses our block-ROW axis (offset by a
 * fixed +25 -- panel-specific, not derived, just matching known-good
 * values) and RASET addresses our block-COLUMN axis, 0-based, full width
 * every time. This is the opposite pairing of the generic MIPI-DBI
 * convention this code guessed at before -- that mismatch, not a timing
 * issue, was the actual cause of the corrupted output. */
static void display_set_window(uint8_t start_row, uint8_t num_rows) {
    uint8_t caset[2] = {(uint8_t) (25 + start_row), (uint8_t) (25 + start_row + num_rows)};
    uint8_t raset[2] = {0x00, DISP_BLOCK_COLS - 1};

    display_write_command(0x2A); /* CASET: our block-row axis, +25 offset */
    display_write_data(caset, sizeof(caset));

    display_write_command(0x2B); /* RASET: our block-column axis, 0-based */
    display_write_data(raset, sizeof(raset));
}

/* Power-mode state machine: the panel starts in Low Power Mode (1Hz
 * refresh, set by the init sequence) to save power at rest. display_flush()
 * wakes it to High Power Mode (16Hz) on demand so new content shows up
 * promptly and uniformly across all rows, and display_tick() drops it back
 * to LPM once it's been idle for a bit. DISP_HPM_IDLE_MS must be at least
 * one full HPM refresh period (1/16Hz = 62.5ms) -- dropping back to LPM
 * before the panel has actually scanned out the new GRAM contents at least
 * once would reintroduce the same up-to-1s staggered-update problem HPM
 * was added to fix, just shifted to whichever rows lost the race back to
 * LPM. 150ms gives that a couple of refresh cycles of margin. */
#define DISP_HPM_IDLE_MS 150

static bool disp_high_power = false; /* matches the init sequence's LPM start state */
static absolute_time_t disp_last_flush_time;

void display_flush(void) {
    if (!disp_high_power) {
        display_write_command(0x38); /* High Power Mode: 16Hz refresh */
        disp_high_power = true;
    }

    /* The panel can't take the whole frame in one window/RAMWR burst --
     * the working AVR reference (buffRows_2_disp) writes 2 block-rows at
     * a time, each as its own complete CASET/RASET/RAMWR transaction, not
     * one giant window over the whole frame. Match that chunk size here.
     * Within each chunk, the data still goes out as a single unbroken SPI
     * transfer (no CS to resync bit alignment if it were split further). */
    for (uint8_t start_row = 0; start_row < DISP_BLOCK_ROWS; start_row += 2) {
        uint8_t rows = (DISP_BLOCK_ROWS - start_row < 2) ? 1 : 2;

        display_set_window(start_row, rows);

        display_write_command(0x2C); /* RAMWR: memory write */
        display_write_data((const uint8_t *) disp_row_buffer[start_row], (size_t) rows * DISP_BLOCK_COLS * 3);
    }

    disp_last_flush_time = get_absolute_time();
}

void display_tick(void) {
    if (!disp_high_power)
        return;
    if (absolute_time_diff_us(disp_last_flush_time, get_absolute_time()) / 1000 >= DISP_HPM_IDLE_MS) {
        display_write_command(0x39); /* Low Power Mode: 1Hz refresh, saves power while idle */
        disp_high_power = false;
    }
}