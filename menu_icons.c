void menu_icon_bits(menu_icon_t icon, uint8_t bits[MENU_ICON_BYTES]) {
    memset(bits, 0, MENU_ICON_BYTES);
    if (icon >= MENU_ICON_COUNT)
        return;
    for (int y = 0; y < MENU_ICON_SIZE; y++)
        for (int x = 0; x < MENU_ICON_SIZE; x++)
            if (art[icon][y][x] == '#')
                bits[y * 4 + x / 8] |= (uint8_t) (0x80 >> (x & 7));
}
