#!/usr/bin/env python3
"""Generates the built-in mini font from Plus42's own characters (bigchars[]
in src/core/core_display.cc): fonts/font_6x8_data.c, and its font sheet
fonts/font_6x8.png -- 16 x 8 cells of 6 x 8, no gaps (96 x 64), black on
white, to start a /FONTS/MINI sheet from (fontsheet.h).

bigchars[c] is 5 column bytes, bit n = row n (top = bit 0); the sixth
column is the gap between characters. Codes 0-127 only. The C table is
display_font_t's layout (font.h): MSB-first rows, packed back to back, 6
bytes per glyph.

Rerun after updating the core: python3 fonts/gen_font_6x8.py
"""
import os
import re
import struct
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src', 'core', 'core_display.cc')
OUT_C = os.path.join(ROOT, 'fonts', 'font_6x8_data.c')
OUT_PNG = os.path.join(ROOT, 'fonts', 'font_6x8.png')

WIDTH, HEIGHT = 6, 8


def glyphs():
    """glyph[code][row][col] = 0/1, for codes 0-127."""
    text = open(SRC).read()
    body = re.search(r'bigchars\[138\]\[5\]\s*=\s*\{(.*?)\n\s*\};', text, re.S).group(1)
    cols = [[int(b, 16) for b in re.findall(r'0x[0-9a-fA-F]{2}', g)]
            for g in re.findall(r'\{([^}]*)\}', body)]
    assert len(cols) == 138 and all(len(c) == 5 for c in cols)
    return [[[(c[x] >> y) & 1 if x < 5 else 0 for x in range(WIDTH)] for y in range(HEIGHT)]
            for c in cols[:128]]


def write_c(font):
    lines = ["/* Generated by fonts/gen_font_6x8.py from Plus42's bigchars[] -- do not edit by hand. */",
             '#include "font.h"',
             '#include "font_6x8.h"',
             '',
             'static const uint8_t font_6x8_bits[] = {']
    for code, g in enumerate(font):
        bits = [b for row in g for b in row]
        data = [sum(bit << (7 - i) for i, bit in enumerate(bits[k:k + 8])) for k in range(0, len(bits), 8)]
        lines.append('    /* %3d */ %s,' % (code, ', '.join('0x%02X' % b for b in data)))
    lines += ['};',
              '',
              'const display_font_t font_6x8 = {',
              '    .width = %d,' % WIDTH,
              '    .height = %d,' % HEIGHT,
              '    .advance = %d,' % WIDTH,
              '    .first_char = 0,',
              '    .last_char = 127,',
              '    .bytes_per_char = %d,' % (WIDTH * HEIGHT // 8),
              '    .data = font_6x8_bits,',
              '};',
              '']
    open(OUT_C, 'w').write('\n'.join(lines))


def write_png(font):
    w, h = 16 * WIDTH, 8 * HEIGHT
    rows = []
    for y in range(h):
        row = bytearray([0])
        for x in range(w):
            g = font[(y // HEIGHT) * 16 + x // WIDTH]
            row.append(0 if g[y % HEIGHT][x % WIDTH] else 255)
        rows.append(bytes(row))

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
    with open(OUT_PNG, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', w, h, 8, 0, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(b''.join(rows), 9)) + chunk(b'IEND', b''))


if __name__ == '__main__':
    font = glyphs()
    write_c(font)
    write_png(font)
