def write_png(path, width, height, gray):
    raw = b''.join(b'\0' + bytes(gray[y * width:(y + 1) * width]) for y in range(height))

    def chunk(kind, data):
        return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))

    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 0, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def main():
    width, height, bpp, color_type, raster = decode_png(SHEET)
    if bpp != 1 or color_type != 0:
        sys.exit('font_10x16.png: expected an 8-bit gray sheet')
    gray = bytearray(raster)
    for code, rows in GLYPHS.items():
        rows = rows + ['.' * W] * (H - len(rows))
        assert len(rows) == H and all(len(r) == W for r in rows), code
        x0, y0 = (code % COLS) * (W + GAP), (code // COLS) * (H + GAP)
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                gray[(y0 + y) * width + x0 + x] = 0 if c == '#' else 255
    write_png(SHEET, width, height, gray)
    subprocess.run([sys.executable, '-I', os.path.join(HERE, 'gen_font.py'), 'font_10x16.png', '--cell-w', str(W),
                    '--cell-h', str(H), '--cols', str(COLS), '--rows', '8', '--gap', str(GAP), '--name',
                    'font_10x16', '--out', 'font_10x16_data.c'], cwd=HERE, check=True)


if __name__ == '__main__':
    main()
