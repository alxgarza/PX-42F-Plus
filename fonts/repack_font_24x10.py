#!/usr/bin/env python3
"""One-off repack of the existing tile-encoded font_24x10 table (in
display.c) into the same continuous-bit-packed display_font_t format the
PNG-sourced fonts use (see font.h, gen_font.py).

font_24x10 has no source PNG -- it's hand-authored directly in the ST7305's
tile layout: 128 glyphs, 30 bytes each, two 15-byte 12-row bands stacked
vertically, each band five 3-byte block-columns wide. Per block-column,
bytes (top, mid, bot) each hold 4 rows x 2 columns, 1 bit/pixel: bit pairs
7:6/5:4/3:2/1:0 are rows 0-3 of that byte's 4-row group, high bit = left
column, low bit = right column (see the confirmed bit layout comment in
display.c, above font_24x10). This script just re-expresses that same
24x10 pixel data with no padding, one bit per pixel, row-major, so it can
share a draw path with font_10x16.
"""
import re
import sys

sys.path.insert(0, __file__.rsplit('/', 1)[0])
from gen_font import pack_bits_msb_first  # noqa: E402

GLYPH_WIDTH = 10
GLYPH_HEIGHT = 24
BLOCK_COLS = 5   # 5 * 2 = 10 columns
BYTES_PER_CHAR = 30
NUM_GLYPHS = 128


def extract_font_array(display_c_path):
    with open(display_c_path) as f:
        text = f.read()
    m = re.search(r'static const uint8_t font_24x10\[\] = \{(.*?)\n\};', text, re.S)
    if not m:
        sys.exit(f'error: could not find font_24x10[] array in {display_c_path}')
    body = m.group(1)
    hex_bytes = re.findall(r'0x([0-9A-Fa-f]{2})', body)
    values = [int(h, 16) for h in hex_bytes]
    expected = NUM_GLYPHS * BYTES_PER_CHAR
    if len(values) != expected:
        sys.exit(f'error: expected {expected} bytes in font_24x10[], found {len(values)}')
    return values


def glyph_bits(glyph_bytes):
    """glyph_bytes: 30 raw bytes for one character, tile-encoded as described
    above. Returns 240 bits, row-major (row 0..23, col 0..9)."""
    bits = [[0] * GLYPH_WIDTH for _ in range(GLYPH_HEIGHT)]
    for band in range(2):
        band_bytes = glyph_bytes[band * 15:(band + 1) * 15]
        for block_col in range(BLOCK_COLS):
            top, mid, bot = band_bytes[block_col * 3:block_col * 3 + 3]
            for byte_val, row_group in ((top, 0), (mid, 4), (bot, 8)):
                for p in range(4):
                    left = (byte_val >> (7 - 2 * p)) & 1
                    right = (byte_val >> (6 - 2 * p)) & 1
                    row = band * 12 + row_group + p
                    bits[row][block_col * 2] = left
                    bits[row][block_col * 2 + 1] = right
    flat = [bits[r][c] for r in range(GLYPH_HEIGHT) for c in range(GLYPH_WIDTH)]
    return flat


def main():
    if len(sys.argv) != 3:
        sys.exit(f'usage: {sys.argv[0]} <display.c> <out font_24x10_data.c>')
    display_c_path, out_path = sys.argv[1], sys.argv[2]

    values = extract_font_array(display_c_path)
    bytes_per_char_out = (GLYPH_WIDTH * GLYPH_HEIGHT + 7) // 8

    packed_glyphs = []
    for code in range(NUM_GLYPHS):
        glyph_bytes = values[code * BYTES_PER_CHAR:(code + 1) * BYTES_PER_CHAR]
        bits = glyph_bits(glyph_bytes)
        packed_glyphs.append(pack_bits_msb_first(bits))

    with open(out_path, 'w') as f:
        f.write(f'/* Generated by fonts/repack_font_24x10.py from display.c\'s original\n')
        f.write(f' * tile-encoded font_24x10[] -- do not edit by hand. */\n')
        f.write('#include "font.h"\n')
        f.write('#include "font_24x10.h"\n\n')
        f.write('static const uint8_t font_24x10_bits[] = {\n')
        for code, glyph in enumerate(packed_glyphs):
            hex_bytes = ', '.join(f'0x{b:02X}' for b in glyph)
            f.write(f'    /* {code:3d} */ {hex_bytes},\n')
        f.write('};\n\n')
        f.write('const display_font_t font_24x10 = {\n')
        f.write(f'    .width = {GLYPH_WIDTH},\n')
        f.write(f'    .height = {GLYPH_HEIGHT},\n')
        f.write(f'    .advance = {GLYPH_WIDTH + 1}, /* glyphs are edge to edge, +1px gap */\n')
        f.write('    .first_char = 0,\n')
        f.write(f'    .last_char = {NUM_GLYPHS - 1},\n')
        f.write(f'    .bytes_per_char = {bytes_per_char_out},\n')
        f.write('    .data = font_24x10_bits,\n')
        f.write('};\n')

    print(f'{out_path}: {NUM_GLYPHS} glyphs, {bytes_per_char_out} bytes/char, '
          f'{bytes_per_char_out * NUM_GLYPHS} bytes total')


if __name__ == '__main__':
    main()
